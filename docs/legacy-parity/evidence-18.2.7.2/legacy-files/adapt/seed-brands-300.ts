async function main() {
  let created = 0;
  let skipped = 0;
  for (const b of BRANDS) {
    const slug = slugify(b.nameEn || b.name);
    const existing = await db.brand.findUnique({ where: { slug } });
    if (existing) { skipped++; continue; }
    await db.brand.create({
      data: {
        name: b.name,
        nameEn: b.nameEn,
        slug,
        country: b.country,
        featured: b.featured || false,
        active: true,
        status: "ACTIVE",
        sortOrder: created,
      },
    });
    created++;
  }
  const total = await db.brand.count();
  console.log(`✅ Created ${created} new brands, skipped ${skipped} existing. Total: ${total}`);
}

main().catch(console.error).finally(() => db.$disconnect());
